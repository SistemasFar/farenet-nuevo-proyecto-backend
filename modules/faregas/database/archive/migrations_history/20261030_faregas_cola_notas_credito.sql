BEGIN;

-- Cola persistente para convertir exclusivamente aprobaciones nuevas de
-- EMITIR_NOTA_CREDITO en una ejecución fiscal. No realiza backfill: las
-- solicitudes históricas aprobadas permanecen sin trabajo hasta que un
-- operador ejecute el procedimiento explícito de recuperación.
CREATE TABLE IF NOT EXISTS public.fg_nota_credito_trabajo (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id bigint NOT NULL
        REFERENCES public.fg_solicitud_operacion(id) ON DELETE RESTRICT,
    certificado_id bigint NOT NULL
        REFERENCES public.fg_certificado(id) ON DELETE RESTRICT,
    facturacion_id bigint NOT NULL
        REFERENCES public.fg_facturacion(id) ON DELETE RESTRICT,
    credito_id bigint
        REFERENCES public.fg_credito(id) ON DELETE RESTRICT,
    empresa_key varchar(40) NOT NULL
        REFERENCES public.fg_empresa(key) ON DELETE RESTRICT,
    planta_key varchar(40) NOT NULL
        REFERENCES public.fg_planta(key) ON DELETE RESTRICT,
    motivo_codigo varchar(2) NOT NULL,
    sustento_aprobado text NOT NULL,
    datos_aprobados jsonb NOT NULL DEFAULT '{}'::jsonb,
    estado varchar(30) NOT NULL DEFAULT 'EN_COLA',
    intentos integer NOT NULL DEFAULT 0,
    disponible_desde timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    propietario_bloqueo uuid,
    bloqueo_hasta timestamptz,
    usuario_ejecutor varchar(255) NOT NULL
        REFERENCES public.fg_usuario(username) ON DELETE RESTRICT,
    ultimo_error_codigo varchar(100),
    ultimo_error_mensaje text,
    resultado jsonb,
    fecha_creacion timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_modificacion timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_inicio timestamptz,
    fecha_finalizacion timestamptz,
    CONSTRAINT uq_fg_nota_credito_trabajo_solicitud UNIQUE (solicitud_id),
    CONSTRAINT ck_fg_nota_credito_trabajo_motivo
        CHECK (motivo_codigo IN ('01', '02', '03')),
    CONSTRAINT ck_fg_nota_credito_trabajo_estado CHECK (estado IN (
        'EN_COLA',
        'ESPERANDO_COMPROBANTE',
        'EMITIENDO',
        'PENDIENTE_SUNAT',
        'ACEPTADA',
        'RECHAZADA',
        'BLOQUEADA',
        'RESULTADO_INCIERTO',
        'ERROR'
    )),
    CONSTRAINT ck_fg_nota_credito_trabajo_intentos CHECK (intentos >= 0)
);

CREATE INDEX IF NOT EXISTS idx_fg_nota_credito_trabajo_pendiente
    ON public.fg_nota_credito_trabajo (estado, disponible_desde, id)
    WHERE estado IN ('EN_COLA', 'ESPERANDO_COMPROBANTE', 'PENDIENTE_SUNAT', 'RESULTADO_INCIERTO', 'ERROR');

CREATE INDEX IF NOT EXISTS idx_fg_nota_credito_trabajo_bloqueo
    ON public.fg_nota_credito_trabajo (bloqueo_hasta)
    WHERE estado = 'EMITIENDO';

COMMIT;
