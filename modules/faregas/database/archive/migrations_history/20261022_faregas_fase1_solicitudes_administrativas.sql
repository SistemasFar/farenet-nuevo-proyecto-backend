BEGIN;

-- FASE 1: infraestructura administrativa. Esta migración no modifica ni
-- ejecuta certificados, comprobantes, pagos, correlativos o documentos PDF.
CREATE TABLE IF NOT EXISTS fg_solicitud_operacion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_operacion varchar(40) NOT NULL,
    certificado_id bigint,
    facturacion_id bigint,
    empresa_key varchar NOT NULL,
    planta_key varchar(20) NOT NULL,
    usuario_solicitante varchar(255) NOT NULL,
    motivo varchar(500) NOT NULL,
    observaciones text,
    estado varchar(40) NOT NULL DEFAULT 'PENDIENTE_APROBACION',
    usuario_decision varchar(255),
    fecha_solicitud timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_decision timestamptz,
    justificacion_decision varchar(1000),
    datos_originales_certificado jsonb,
    datos_originales_comprobante jsonb,
    datos_propuestos jsonb,
    fecha_emision_original date,
    resultado_tecnico jsonb,
    resultado_fiscal jsonb,
    idempotencia_clave uuid NOT NULL,
    version integer NOT NULL DEFAULT 1,
    fecha_creacion timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_modificacion timestamptz,
    CONSTRAINT fk_fg_solicitud_certificado
        FOREIGN KEY (certificado_id) REFERENCES fg_certificado(id) ON DELETE RESTRICT,
    CONSTRAINT fk_fg_solicitud_facturacion
        FOREIGN KEY (facturacion_id) REFERENCES fg_facturacion(id) ON DELETE RESTRICT,
    CONSTRAINT fk_fg_solicitud_empresa
        FOREIGN KEY (empresa_key) REFERENCES fg_empresa(key) ON DELETE RESTRICT,
    CONSTRAINT fk_fg_solicitud_planta
        FOREIGN KEY (planta_key) REFERENCES fg_planta(key) ON DELETE RESTRICT,
    CONSTRAINT fk_fg_solicitud_solicitante
        FOREIGN KEY (usuario_solicitante) REFERENCES fg_usuario(username) ON DELETE RESTRICT,
    CONSTRAINT fk_fg_solicitud_decisor
        FOREIGN KEY (usuario_decision) REFERENCES fg_usuario(username) ON DELETE RESTRICT,
    CONSTRAINT ck_fg_solicitud_tipo CHECK (tipo_operacion IN (
        'ANULAR_CERTIFICADO', 'ANULAR_COMPROBANTE', 'ANULAR_AMBOS',
        'RECTIFICAR_CERTIFICADO', 'RECTIFICAR_COMPROBANTE', 'RECTIFICAR_AMBOS'
    )),
    CONSTRAINT ck_fg_solicitud_estado CHECK (estado IN (
        'PENDIENTE_APROBACION', 'APROBADA', 'RECHAZADA', 'CANCELADA',
        'EN_EJECUCION', 'COMPLETADA', 'ERROR', 'REQUIERE_INTERVENCION'
    )),
    CONSTRAINT ck_fg_solicitud_documentos CHECK (
        (tipo_operacion IN ('ANULAR_CERTIFICADO', 'RECTIFICAR_CERTIFICADO') AND certificado_id IS NOT NULL)
        OR (tipo_operacion IN ('ANULAR_COMPROBANTE', 'RECTIFICAR_COMPROBANTE') AND facturacion_id IS NOT NULL)
        OR (tipo_operacion IN ('ANULAR_AMBOS', 'RECTIFICAR_AMBOS') AND certificado_id IS NOT NULL AND facturacion_id IS NOT NULL)
    ),
    CONSTRAINT ck_fg_solicitud_motivo CHECK (btrim(motivo) <> ''),
    CONSTRAINT ck_fg_solicitud_version CHECK (version > 0),
    CONSTRAINT ck_fg_solicitud_no_autoaprobacion CHECK (
        estado <> 'APROBADA' OR usuario_decision IS DISTINCT FROM usuario_solicitante
    ),
    CONSTRAINT uq_fg_solicitud_idempotencia UNIQUE (usuario_solicitante, idempotencia_clave)
);

CREATE TABLE IF NOT EXISTS fg_solicitud_operacion_evento (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id bigint NOT NULL,
    tipo_evento varchar(50) NOT NULL,
    estado_anterior varchar(40),
    estado_posterior varchar(40) NOT NULL,
    usuario_responsable varchar(255) NOT NULL,
    fecha_evento timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    comentario text,
    metadatos jsonb,
    CONSTRAINT fk_fg_solicitud_evento_solicitud
        FOREIGN KEY (solicitud_id) REFERENCES fg_solicitud_operacion(id) ON DELETE RESTRICT,
    CONSTRAINT fk_fg_solicitud_evento_usuario
        FOREIGN KEY (usuario_responsable) REFERENCES fg_usuario(username) ON DELETE RESTRICT,
    CONSTRAINT ck_fg_solicitud_evento_anterior CHECK (
        estado_anterior IS NULL OR estado_anterior IN (
            'PENDIENTE_APROBACION', 'APROBADA', 'RECHAZADA', 'CANCELADA',
            'EN_EJECUCION', 'COMPLETADA', 'ERROR', 'REQUIERE_INTERVENCION'
        )
    ),
    CONSTRAINT ck_fg_solicitud_evento_posterior CHECK (estado_posterior IN (
        'PENDIENTE_APROBACION', 'APROBADA', 'RECHAZADA', 'CANCELADA',
        'EN_EJECUCION', 'COMPLETADA', 'ERROR', 'REQUIERE_INTERVENCION'
    ))
);

CREATE INDEX IF NOT EXISTS idx_fg_solicitud_planta
    ON fg_solicitud_operacion (planta_key, fecha_solicitud DESC);
CREATE INDEX IF NOT EXISTS idx_fg_solicitud_empresa
    ON fg_solicitud_operacion (empresa_key, fecha_solicitud DESC);
CREATE INDEX IF NOT EXISTS idx_fg_solicitud_estado
    ON fg_solicitud_operacion (estado, fecha_solicitud DESC);
CREATE INDEX IF NOT EXISTS idx_fg_solicitud_tipo
    ON fg_solicitud_operacion (tipo_operacion, fecha_solicitud DESC);
CREATE INDEX IF NOT EXISTS idx_fg_solicitud_solicitante
    ON fg_solicitud_operacion (usuario_solicitante, fecha_solicitud DESC);
CREATE INDEX IF NOT EXISTS idx_fg_solicitud_evento_historial
    ON fg_solicitud_operacion_evento (solicitud_id, fecha_evento, id);

-- Una solicitud rechazada, cancelada, completada o en error no bloquea una
-- solicitud posterior. Las pendientes, aprobadas sin ejecutar, en ejecución o
-- que requieren intervención sí son incompatibles sobre el mismo documento.
CREATE UNIQUE INDEX IF NOT EXISTS uq_fg_solicitud_activa_certificado
    ON fg_solicitud_operacion (certificado_id)
    WHERE certificado_id IS NOT NULL
      AND estado IN ('PENDIENTE_APROBACION', 'APROBADA', 'EN_EJECUCION', 'REQUIERE_INTERVENCION');

CREATE UNIQUE INDEX IF NOT EXISTS uq_fg_solicitud_activa_facturacion
    ON fg_solicitud_operacion (facturacion_id)
    WHERE facturacion_id IS NOT NULL
      AND estado IN ('PENDIENTE_APROBACION', 'APROBADA', 'EN_EJECUCION', 'REQUIERE_INTERVENCION');

CREATE OR REPLACE FUNCTION fg_bloquear_mutacion_solicitud_evento()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'El historial de solicitudes administrativas es inmutable.'
        USING ERRCODE = '55000';
END;
$$;

DROP TRIGGER IF EXISTS trg_fg_solicitud_evento_inmutable ON fg_solicitud_operacion_evento;
CREATE TRIGGER trg_fg_solicitud_evento_inmutable
BEFORE UPDATE OR DELETE ON fg_solicitud_operacion_evento
FOR EACH ROW EXECUTE FUNCTION fg_bloquear_mutacion_solicitud_evento();

