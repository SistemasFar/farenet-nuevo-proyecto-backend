-- 1. Verificar y asegurar tabla de cuotas de facturación fg_facturacion_cuota
CREATE TABLE IF NOT EXISTS fg_facturacion_cuota (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facturacion_id BIGINT NOT NULL,
    numero_cuota INTEGER NOT NULL,
    fecha_pago DATE NOT NULL,
    importe NUMERIC(14,2) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    fecha_creacion TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_modificacion TIMESTAMP WITHOUT TIME ZONE NULL,
    CONSTRAINT fk_fg_facturacion_cuota_facturacion
        FOREIGN KEY (facturacion_id) REFERENCES fg_facturacion(id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT uq_fg_facturacion_cuota_numero
        UNIQUE (facturacion_id, numero_cuota),
    CONSTRAINT ck_fg_facturacion_cuota_numero CHECK (numero_cuota > 0),
    CONSTRAINT ck_fg_facturacion_cuota_importe CHECK (importe > 0),
    CONSTRAINT ck_fg_facturacion_cuota_estado
        CHECK (estado IN ('PENDIENTE', 'PAGADA', 'ANULADA'))
);

-- 2. Índice de vencimiento y ordenación de cuotas
CREATE INDEX IF NOT EXISTS ix_fg_facturacion_cuota_vencimiento
    ON fg_facturacion_cuota (facturacion_id, fecha_pago, numero_cuota);

-- 3. Asegurar columnas de crédito en fg_facturacion
ALTER TABLE fg_facturacion
    ADD COLUMN IF NOT EXISTS condicion_pago VARCHAR(20) DEFAULT 'CONTADO',
    ADD COLUMN IF NOT EXISTS fecha_vencimiento DATE;

-- 4. Asegurar columnas de crédito en fg_orden_pago
ALTER TABLE fg_orden_pago
    ADD COLUMN IF NOT EXISTS fecha_inicio_credito DATE,
    ADD COLUMN IF NOT EXISTS fecha_vencimiento_credito DATE;
