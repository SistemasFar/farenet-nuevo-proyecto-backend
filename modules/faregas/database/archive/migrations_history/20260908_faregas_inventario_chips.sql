FROM fg_producto_inventariable pi
JOIN fg_planta p ON p.empresa_key = 'FAREGAS' AND p.activo = TRUE
WHERE pi.codigo = 'CHIP'
ON CONFLICT (producto_inventariable_id, planta_key) DO UPDATE
SET precio = EXCLUDED.precio, activo = TRUE, fecha_modificacion = CURRENT_TIMESTAMP;

